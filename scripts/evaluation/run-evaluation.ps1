<#
.SYNOPSIS
    Evaluation runner for the MCP Playwright test framework.
.DESCRIPTION
    Orchestrates Pester tests, generates reports, and produces
    a structured evaluation output compatible with the evidence/
    directory conventions.
.PARAMETER Tag
    Run only tests matching a specific Pester tag (e.g., "Infrastructure", "Functional").
.PARAMETER OutputDir
    Directory for evaluation reports. Defaults to scripts/evaluation/results/.
.PARAMETER CI
    Run in CI mode: minimal output, exit code only.
.PARAMETER ListTags
    List all available test tags and exit.
.EXAMPLE
    .\run-evaluation.ps1
    .\run-evaluation.ps1 -Tag Infrastructure
    .\run-evaluation.ps1 -Tag RoundTrip
    .\run-evaluation.ps1 -CI
    .\run-evaluation.ps1 -ListTags
#>

param(
    [string]$Tag,
    [string]$OutputDir,
    [switch]$CI,
    [switch]$ListTags
)

$ErrorActionPreference = "Continue"

# --- Paths ---
$Script:EvalRoot = $PSScriptRoot
$Script:RepoRoot = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$Script:DefaultOutput = Join-Path $PSScriptRoot "results"
$Script:OutputDir = if ($OutputDir) { $OutputDir } else { $Script:DefaultOutput }

# Available test file paths
$Script:TestFiles = @(
    (Join-Path $Script:EvalRoot "infrastructure.Tests.ps1")
    (Join-Path $Script:EvalRoot "functional.Tests.ps1")
    (Join-Path $Script:EvalRoot "production-path.Tests.ps1")
)

# Available tags
$Script:AllTags = @(
    "Infrastructure", "Parsing", "Comparison", "RoundTrip", "Hosts", "Package",
    "Duplicates", "Fixtures",
    "Functional", "Dataset", "DatasetStructural", "DatasetFunctional", "Scripts",
    "ProductionPath", "Install", "Idempotent", "Malformed", "Verify"
)

# --- List Tags ---
if ($ListTags) {
    Write-Output "Available evaluation tags:"
    foreach ($t in $Script:AllTags) { Write-Output "  - $t" }
    Write-Output ""
    Write-Output "Usage: .\run-evaluation.ps1 -Tag <TagName>"
    exit 0
}

# --- Check Pester ---
$pesterAvailable = Get-Module -ListAvailable -Name Pester | Where-Object { $_.Version -ge [System.Version]"5.0.0" }
if (-not $pesterAvailable) {
    if ($CI) {
        Write-Output "[EVAL] Pester 5+ not found. Install with: Install-Module Pester -Force -SkipPublisherCheck"
        exit 2
    }
    Write-Output "[EVAL] Pester 5+ not found. Attempting auto-install..."
    try {
        Install-Module Pester -Force -SkipPublisherCheck -AllowClobber -Scope CurrentUser 2>&1 | Out-Null
        Import-Module Pester -Force
        Write-Output "[EVAL] Pester installed successfully."
    } catch {
        Write-Output "[FAIL] Could not install Pester: $_"
        Write-Output "       Install manually: Install-Module Pester -Force -SkipPublisherCheck"
        exit 2
    }
}

Import-Module Pester -Force -PassThru | Out-Null

# --- Ensure output directory ---
New-Item -ItemType Directory -Path $Script:OutputDir -Force | Out-Null

# --- Build test configuration ---
$config = New-PesterConfiguration
$config.Run.Path = $Script:TestFiles
$config.Run.Exit = $true
$config.Run.PassThru = $true
$config.Output.Verbosity = if ($CI) { "None" } else { "Detailed" }
$config.TestResult.Enabled = $true
$config.TestResult.OutputFormat = "NUnitXml"
$config.TestResult.OutputPath = Join-Path $Script:OutputDir "evaluation-results.xml"
$config.CodeCoverage.Enabled = $false

if ($Tag) {
    $config.Filter.Tag = $Tag
}

# --- Run ---
Write-Output "============================================"
Write-Output "  MCP Playwright Evaluation Framework"
Write-Output "  Repo: $Script:RepoRoot"
if ($Tag) { Write-Output "  Tag Filter: $Tag" }
Write-Output "  Output: $($Script:OutputDir)"
Write-Output "============================================"
Write-Output ""

$result = Invoke-Pester -Configuration $config

# --- Generate summary report ---
$reportPath = Join-Path $Script:OutputDir "evaluation-report.md"
$total = $result.TotalCount
$passed = $result.PassedCount
$failed = $result.FailedCount
$skipped = $result.SkippedCount
$notRun = $result.NotRunCount

$report = @"
# MCP Playwright Evaluation Report

**Date:** $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
**Pester Version:** $((Get-Module Pester).Version)
**Tag Filter:** $(if ($Tag) { $Tag } else { "All" })

## Summary

| Metric | Value |
|--------|-------|
| Total Tests | $total |
| Passed | $passed |
| Failed | $failed |
| Skipped | $skipped |
| Not Run | $notRun |
| Pass Rate | $(if ($total -gt 0) { "{0:P1}" -f ($passed / $total) } else { "N/A" }) |

## Test Results

$(if ($failed -gt 0) {
@"
### Failed Tests

$($result.Failed | ForEach-Object { "- [$($_.Describe)] $($_.Name) :: $($_.ErrorRecord.Exception.Message)" } | Out-String)
"@
} else {
"### All tests passed."
})

$(if ($skipped -gt 0) {
@"
### Skipped Tests

$($result.Skipped | ForEach-Object { "- [$($_.Describe)] $($_.Name) :: $($_.SkippedBecause)" } | Out-String)
"@
})

---

*Generated by scripts/evaluation/run-evaluation.ps1*
"@

$report | Out-File $reportPath -Encoding UTF8 -Force

# --- Final output ---
if ($CI) {
    Write-Output "[EVAL] Passed: $passed / $total | Failed: $failed | Skipped: $skipped | Report: $reportPath"
} else {
    Write-Output ""
    Write-Output "=== Evaluation Complete ==="
    Write-Output "Total:  $total"
    Write-Output "Passed: $passed"
    Write-Output "Failed: $failed"
    Write-Output "Skipped: $skipped"
    if ($notRun -gt 0) { Write-Output "Not Run: $notRun" }
    Write-Output "Report: $reportPath"
    Write-Output ""
    Write-Output "Detailed results: $($config.TestResult.OutputPath)"
}

if ($failed -gt 0 -and $CI) { exit 1 }
exit 0
